const idx = (lang) => Math.max(0, ['ky', 'ru', 'en'].indexOf(lang));

export function translate(lang, key) {
  return T[key]?.[idx(lang)] ?? key;
}

export function catName(lang, slug) {
  return CATS[slug]?.[idx(lang)] ?? slug.replace(/-/g, ' ');
}

export const CATEGORY_SLUGS = Object.keys(CATS);

export function formatPrice(n, lang) {
  const s = Math.round(n).toLocaleString(lang === 'en' ? 'en-US' : 'ru-RU').replace(/ /g, ' ');
  return lang === 'en' ? `${s} KGS` : `${s} сом`;
}

export function formatDate(d, lang) {
  return new Date(d).toLocaleDateString(lang === 'en' ? 'en-GB' : lang === 'ky' ? 'ky-KG' : 'ru-RU', { day: 'numeric', month: 'short', year: 'numeric' });
}
